// The one-shot microsecond timer of platform/stm32/oneshot.h on TIM7: a basic 16-bit timer counting at 1 MHz in
// one-pulse mode, its interrupt at the modem interrupts' priority.
//
// What the callers rely on, and how it is met here:
// - A wait that is replaced or stopped never calls back. Start and stop clear the update flag, and the handler calls
//   only when it finds the flag set, so an interrupt that was already pending finds nothing.
// - The callback may start the next wait before it does its work, and a wait that runs out meanwhile calls it again.
//   The handler clears the flag before the call, never after: the flag a new wait sets while the callback runs stays
//   set and brings the handler back.
// - No wait is shorter than asked. Every start restarts the prescaler with the counter (an update event generated by
//   software, which with URS set raises no flag), so the first count is a whole microsecond.
#include <stddef.h>
#include "oneshot.h"
#include "platform.h"
#include "periph/pwm.h"

#define ONESHOT_IRQ_PRIORITY	5	// the modem lines' (hrc/dmr_glue.c): neither preempts the other

static void (*callback)(void);

void stm32_oneshot_init(void (*fn)(void))
{
	__HAL_RCC_TIM7_CLK_ENABLE();
	TIM7->CR1 = TIM_CR1_URS;	// stopped; only a counter overflow sets the update flag
	TIM7->DIER = 0;
	callback = fn;
	// 1 MHz from the timer's clock (96 MHz with the usual table; a clock that is not whole MHz counts a little off)
	const uint32_t mhz = (stm32_pwm_timer_hz(TIM7) + 500000u) / 1000000u;
	TIM7->PSC = mhz > 1u ? mhz - 1u : 0u;
	TIM7->ARR = 0xFFFFu;
	TIM7->EGR = TIM_EGR_UG;		// the prescaler into use
	TIM7->SR = 0;			// nothing due: the first handler must not find a flag
	TIM7->DIER = TIM_DIER_UIE;
	HAL_NVIC_SetPriority(TIM7_IRQn, ONESHOT_IRQ_PRIORITY, 0);
	HAL_NVIC_EnableIRQ(TIM7_IRQn);
}

void stm32_oneshot_start(uint32_t us)
{
	if (us > 0xFFFFu) {
		us = 0xFFFFu;
	}
	TIM7->CR1 = TIM_CR1_URS;	// stopped: a wait still running is replaced
	// The counter overflows us counts after the update event below. A counter does not run with a reload value of
	// 0 (RM0433, TIMx_ARR), so the shortest wait counts from 1 to the reload value 1
	TIM7->ARR = us > 1u ? us - 1u : 1u;
	TIM7->EGR = TIM_EGR_UG;		// counter and prescaler from 0
	if (us <= 1u) {
		TIM7->CNT = 1u;
	}
	TIM7->SR = 0;			// the flag of the wait this one replaces
	TIM7->CR1 = TIM_CR1_URS | TIM_CR1_OPM | TIM_CR1_CEN;
}

void stm32_oneshot_stop(void)
{
	TIM7->CR1 = TIM_CR1_URS;
	TIM7->SR = 0;
}

void TIM7_IRQHandler(void)
{
	if ((TIM7->SR & TIM_SR_UIF) == 0) {
		return;		// stopped or started again since the interrupt was raised
	}
	TIM7->SR = 0;		// before the call: the callback may start the next wait, whose flag must survive it
	if (callback != NULL) {
		callback();
	}
}
